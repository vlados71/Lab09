// Сума ряду 2 * sum( x^(2n+1) / (2n+1) ) з точністю e.
// Вхід: глобальні x, e. Вихід: глобальні s (сума) і n.
// Після виконання n - індекс останнього доданку, тобто кількість
// просумованих доданків дорівнює n + 1 (доданок a(0) теж рахується).
void nsSum::sum()
{
    n = 0;
    a = 2 * x;              // перший доданок a(0) = 2x
    s = a;
    do
    {
        n++;
        dod();              // виклик процедури обчислення доданку
        s += a;
    } while (fabs(a) > e);
}