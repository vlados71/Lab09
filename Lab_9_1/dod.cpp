using namespace nsVar;

// Доданок ряду: a(n) = 2 * x^(2n+1) / (2n+1), перший доданок a(0) = 2x.
// Коефіцієнт рекурентності:
//   R(n) = a(n) / a(n-1) = x^2 * (2n - 1) / (2n + 1)
// Вхід: глобальні x, n (індекс нового доданку), a (попередній доданок).
// Вихід: глобальна a (новий доданок).
void nsDod::dod()
{
    a *= x * x * (2 * n - 1) / (2 * n + 1);
}